    [Test, Order(0)]
    public async Task Step00_CreateSequenceFile()
    {
        // Close ALL currently loaded sequence files that match our path so that
        // the TestStand engine releases any file lock from a previous run.
        try
        {
            var loaded = await _ts.GetLoadedSequenceFilesAsync();
            foreach (var f in loaded)
                if (string.Equals(f.FilePath, SeqFilePath, StringComparison.OrdinalIgnoreCase))
                    try { await _ts.CloseSequenceFileAsync(f.FilePath); } catch { }
        }
        catch { }

        // Delete old file so we always start clean
        if (File.Exists(SeqFilePath))
        {
            // Small retry loop in case the engine needs a moment to release the handle
            for (int i = 0; i < 5; i++)
            {
                try { File.Delete(SeqFilePath); break; }
                catch { System.Threading.Thread.Sleep(300); }
            }
        }

        await _ts.CreateSequenceFileAsync(SeqFilePath);
        await _ts.SetFilePropertiesAsync(SeqFilePath,
            comment: "TestData — one sequence per TestStand step-type category. " +
                     "Auto-generated by TestDataBuilderTests.",
            version: "1.0.0");

        Assert.That(File.Exists(SeqFilePath), Is.True, "Sequence file must be written to disk");
        TestContext.WriteLine($"Created: {SeqFilePath}");
    }

