    // ── MainSequence — SequenceCall steps to every sequence above ─────────────

    [Test, Order(17)]
    public async Task Step17_Build_MainSequence_WithAllSubsequenceCalls()
    {
        // All sequences created by previous steps
        var subSequences = new[]
        {
            ("Seq_Statement",               "Call_Statement",
             "Runs all Statement step examples."),
            ("Seq_Action",                  "Call_Action",
             "Runs all Action step examples."),
            ("Seq_MessagePopup",            "Call_MessagePopup",
             "Runs all MessagePopup step examples."),
            ("Seq_CallExecutable",          "Call_CallExecutable",
             "Runs all CallExecutable step examples."),
            ("Seq_SequenceCall",            "Call_SequenceCall",
             "Runs all SequenceCall step examples."),
            ("Seq_NumericLimitTest",        "Call_NumericLimitTest",
             "Runs all NumericLimitTest step examples."),
            ("Seq_StringValueTest",         "Call_StringValueTest",
             "Runs all StringValueTest step examples."),
            ("Seq_PassFailTest",            "Call_PassFailTest",
             "Runs all PassFailTest step examples."),
            ("Seq_MultipleNumericLimitTest","Call_MultipleNumericLimitTest",
             "Runs all NI_MultipleNumericLimitTest step examples."),
            ("Seq_FlowIf",                  "Call_FlowIf",
             "Runs the If / ElseIf / Else / End example sequence."),
            ("Seq_FlowWhile",               "Call_FlowWhile",
             "Runs the While / End example sequence."),
            ("Seq_FlowDoWhile",             "Call_FlowDoWhile",
             "Runs the DoWhile / End example sequence."),
            ("Seq_FlowFor",                 "Call_FlowFor",
             "Runs the For / End example sequence."),
            ("Seq_FlowForEach",             "Call_FlowForEach",
             "Runs the ForEach / End example sequence."),
            ("Seq_FlowSelect",              "Call_FlowSelect",
             "Runs the Select / Case / End example sequence."),
            ("Seq_FlowBreakContinue",       "Call_FlowBreakContinue",
             "Runs the Break / Continue example sequence."),
        };

        foreach (var (targetSeq, stepName, comment) in subSequences)
        {
            await _ts.InsertStepAsync(SeqFilePath, "MainSequence", "Main",
                "SequenceCall", stepName);
            await _ts.SetStepCommentAsync(SeqFilePath, "MainSequence", "Main",
                stepName, comment);
            await _ts.SetSequenceCallTargetAsync(SeqFilePath, "MainSequence", "Main",
                stepName, targetSeq);
        }

        await _ts.SaveSequenceFileAsync(SeqFilePath);

        // Verify
        await _ts.OpenSequenceFileAsync(SeqFilePath);
        var mainSteps = await _ts.GetStepsAsync(SeqFilePath, "MainSequence");

        foreach (var (_, stepName, comment) in subSequences)
        {
            var s = mainSteps.FirstOrDefault(x => x.Name == stepName);
            Assert.That(s, Is.Not.Null,
                $"MainSequence should contain call step '{stepName}'");
            Assert.That(s!.StepType, Is.EqualTo("SequenceCall"),
                $"'{stepName}' should be a SequenceCall step");
            Assert.That(s.Description, Is.EqualTo(comment),
                $"Comment for '{stepName}' did not round-trip");
        }

        TestContext.WriteLine($"TestData.seq saved to: {SeqFilePath}");
        TestContext.WriteLine($"  MainSequence call steps: {mainSteps.Count}");
    }
