/// <summary>
/// Builds <c>TestData.seq</c>.
///
/// One sequence per step-type category is created in the Main step group.
/// Each step receives a descriptive name and a comment.
/// After building every sequence the names and comments are read back and
/// asserted to prove the complete write→save→read round-trip.
///
/// The Main sequence receives a <c>SequenceCall</c> step for every other
/// sequence in the file.
/// </summary>
[TestFixture]
[Category("TestData")]
public class TestDataBuilderTests
{
    // ── Path ──────────────────────────────────────────────────────────────────
    private static readonly string SeqFilePath = Path.GetFullPath(
        Path.Combine(
            TestContext.CurrentContext.TestDirectory,
            @"..\..\..\..\"   // Test\TestExecution → project root
            + "TestData.seq"));

    // Use the assembly-level shared service — avoids per-fixture connect/disconnect
    // which causes COM STA/MTA finalizer crashes when creating multiple engine instances.
    private ITestStandService _ts => AssemblySetup.Ts;

    // ── Internal helpers ──────────────────────────────────────────────────────

    /// <summary>Tuple that pairs a step name with its expected type and comment.</summary>
    private sealed class StepDef
    {
        public string Type    { get; }
        public string Name    { get; }
        public string Comment { get; }
        public StepDef(string type, string name, string comment)
        { Type = type; Name = name; Comment = comment; }
    }

    private async Task BuildSequenceAsync(string seqName, IEnumerable<StepDef> steps)
    {
        await _ts.InsertSequenceAsync(SeqFilePath, seqName);
        foreach (var s in steps)
        {
            await _ts.InsertStepAsync(SeqFilePath, seqName, "Main", s.Type, s.Name);
            await _ts.SetStepCommentAsync(SeqFilePath, seqName, "Main", s.Name, s.Comment);
        }
    }

    private async Task VerifySequenceAsync(string seqName, IEnumerable<StepDef> expected)
    {
        // Re-open the saved file to confirm persistence
        await _ts.OpenSequenceFileAsync(SeqFilePath);
        var steps = await _ts.GetStepsAsync(SeqFilePath, seqName);

        foreach (var exp in expected)
        {
            var actual = steps.FirstOrDefault(s => s.Name == exp.Name);
            Assert.That(actual,             Is.Not.Null,
                $"[{seqName}] Step '{exp.Name}' not found after save+reload");
            Assert.That(actual!.StepType,   Is.EqualTo(exp.Type),
                $"[{seqName}] '{exp.Name}' — wrong step type");
            Assert.That(actual.Description, Is.EqualTo(exp.Comment),
                $"[{seqName}] '{exp.Name}' — comment did not round-trip");
        }
    }

